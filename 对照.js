const assert = require("assert");
const { 分温 } = require("./分温.js");

function 核对(名字, 底, 顶, 期望) {
  const 得到 = 分温(底, 顶).出;
  if (得到 !== 期望) {
    process.stderr.write(名字 + "没对上\n");
    process.exit(1);
  }
}

核对("现有", "1000", "1220", "正烧");
核对("缺温-底空", "", "1220", "缺温");
核对("缺温-顶空", "1000", "", "缺温");
核对("分界-不到1180", "1000", "1179", "欠烧");
核对("分界-正好1180", "1000", "1180", "正烧");
核对("分界-正好1260", "1000", "1260", "正烧");
核对("分界-过了1260", "1000", "1261", "过烧");
核对("温度倒着", "1300", "1200", "温度倒着");
process.stdout.write("对照通过\n");
