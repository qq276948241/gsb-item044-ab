const assert = require("assert");
const { 分温 } = require("./分温.js");

function 核对(名字, 底, 顶, 期望) {
  const 得到 = 分温(底, 顶).出;
  if (得到 !== 期望) {
    process.stderr.write(名字 + "没对上\n");
    process.exit(1);
  }
}

核对("现有", "1000", "1220", "正烧");
核对("顶温卡1180分界", "1000", "1180", "正烧");
核对("顶温卡1260分界", "1000", "1260", "正烧");
核对("底温没填", "", "1220", "缺温");
核对("顶温没填", "1000", "", "缺温");
核对("底温比顶温高", "1300", "1000", "温度倒着");
process.stdout.write("对照通过\n");
